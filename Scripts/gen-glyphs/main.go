func main() {
	root := flag.String("root", ".", "repository root")
	out := flag.String("out", "internal/app/glyphs_gen.go", "output file, relative to root")
	flag.Parse()
	if err := run(*root, *out); err != nil {
		fmt.Fprintln(os.Stderr, "gen-glyphs:", err)
		os.Exit(1)
	}
}

func run(root, out string) error {
	icons, err := fetchIcons()
	if err != nil {
		return err
	}
	src, err := render(icons)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(root, out), src, 0o644); err != nil {
		return err
	}
	return writeProviders(root)
}

// render builds the Go source from the SVG files by icon name.
func render(icons map[string]string) ([]byte, error) {
	names := make([]string, 0, len(glyphs))
	for n := range glyphs {
		names = append(names, n)
	}
	sort.Strings(names)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by Scripts/gen-glyphs from Remix Icon %s\n", remixVersion)
	b.WriteString("// (https://remixicon.com, Remix Icon License v1.0). DO NOT EDIT.\n\npackage app\n\nvar (\n")
	for _, n := range names {
		svg, ok := icons[glyphs[n]]
		if !ok {
			return nil, fmt.Errorf("icon %q (%s) is not in Remix Icon %s", glyphs[n], n, remixVersion)
		}
		body, err := svgBody(svg)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", glyphs[n], err)
		}
		fmt.Fprintf(&b, "\t%s = remix(`%s`) // %s\n", n, body, glyphs[n])
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

var (
	svgInner  = regexp.MustCompile(`(?s)<svg[^>]*>(.*)</svg>`)
	emptyPath = regexp.MustCompile(`<path fill="none" d="M0 0h24v24H0z"\s*/?>(</path>)?`)
)

// svgBody is the drawing of an icon file without its frame.
func svgBody(svg string) (string, error) {
	m := svgInner.FindStringSubmatch(svg)
	if m == nil {
		return "", fmt.Errorf("no <svg> element")
	}
	body := strings.TrimSpace(m[1])
	body = emptyPath.ReplaceAllString(body, "")
	body = strings.ReplaceAll(body, "></path>", "/>")
	if strings.Contains(body, "`") {
		return "", fmt.Errorf("backtick in icon")
	}
	return strings.TrimSpace(body), nil
}

// fetchIcons returns the SVG source of every icon by file name without
// extension, downloading the npm package once.
func fetchIcons() (map[string]string, error) {
	cache := filepath.Join(os.TempDir(), "quosparr-icons")
	if err := os.MkdirAll(cache, 0o755); err != nil {
		return nil, err
	}
	tgz := filepath.Join(cache, "remixicon-"+remixVersion+".tgz")
	if _, err := os.Stat(tgz); err != nil {
		if err := download("https://registry.npmjs.org/remixicon/-/remixicon-"+remixVersion+".tgz", tgz); err != nil {
			return nil, err
		}
	}
	f, err := os.Open(tgz)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	zr, err := gzip.NewReader(f)
	if err != nil {
		return nil, err
	}
	icons := map[string]string{}
	tr := tar.NewReader(zr)
	for {
		h, err := tr.Next()
		if err == io.EOF {
			return icons, nil
		}
		if err != nil {
			return nil, err
		}
		if h.Typeflag != tar.TypeReg || !strings.HasPrefix(h.Name, "package/icons/") || path.Ext(h.Name) != ".svg" {
			continue
		}
		data, err := io.ReadAll(tr)
		if err != nil {
			return nil, err
		}
		icons[strings.TrimSuffix(path.Base(h.Name), ".svg")] = string(data)
	}
}

func download(url, dest string) error {
	client := &http.Client{Timeout: 5 * time.Minute}
	resp, err := client.Get(url)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("download %s: %s", url, resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		return err
	}
	return os.WriteFile(dest, data, 0o644)
}
